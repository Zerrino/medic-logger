#!/usr/bin/env python3
"""Generate Android resources and a typed resource lookup from reviewed translations."""
import hashlib
import json
from pathlib import Path
import re
import xml.etree.ElementTree as ET

root=Path(__file__).resolve().parents[1]
messages=json.loads((root/'app/translations.json').read_text())
plurals={
    '%d reminders':('%d reminder',0),
    '%d doses':('%d dose',0),
    '%d doses are already active for this medicine. Log a separate dose?':('%d dose is already active for this medicine. Log a separate dose?',0),
    '%d doses this month':('%d dose this month',0),
    '%d events':('%d event',0),
    '%d events selected':('%d event selected',0),
    '%d saved medicines':('%d saved medicine',0),
    '%d of %d doses':('%d of %d dose',1)
}
singular_only={value[0] for value in plurals.values()}
def key(s):return 'ui_'+hashlib.sha256(s.encode()).hexdigest()[:12]
def placeholders(s):return re.findall(r'%(?:\d+\$)?[ds]',s)
def android(s):
    count=0
    def positional(m):
        nonlocal count
        count+=1
        return f'%{count}${m.group(1)}'
    s=re.sub(r'%([ds])',positional,s)
    return s.replace('\\','\\\\').replace("'","\\'").replace('"','\\"').replace('\n','\\n')
for lang,index in [('en',None),('fr',0),('pt',1),('zh',2)]:
    resources=ET.Element('resources')
    for english,translations in sorted(messages.items()):
        if english in singular_only:continue
        assert len(translations)==3 and all(translations),english
        translated=english if index is None else translations[index]
        assert [p[-1] for p in placeholders(english)]==[p[-1] for p in placeholders(translated)],english
        if english in plurals:
            singular=plurals[english][0]
            one=singular if index is None else messages[singular][index]
            node=ET.SubElement(resources,'plurals',name=key(english))
            if lang!='zh':ET.SubElement(node,'item',quantity='one').text=android(one)
            if lang in ('fr','pt'):ET.SubElement(node,'item',quantity='many').text=android(translated)
            ET.SubElement(node,'item',quantity='other').text=android(translated)
        else:
            ET.SubElement(resources,'string',name=key(english)).text=android(translated)
    folder=root/'app/src/main/res'/('values' if lang=='en' else 'values-'+lang)
    folder.mkdir(parents=True,exist_ok=True)
    ET.indent(resources)
    ET.ElementTree(resources).write(folder/'ui_strings.xml',encoding='utf-8',xml_declaration=True)
source='''package fr.mediclogger.app;

// Generated by scripts/generate-i18n.py. Edit app/translations.json instead.
import android.content.Context;
import java.util.HashMap;
import java.util.Map;

public final class I18n {
    private static final Map<String,Integer> IDS=new HashMap<>();
    private static final Map<Integer,Integer> QUANTITIES=new HashMap<>();
    static {
'''
for english in sorted(messages):
    if english in singular_only:continue
    kind='plurals' if english in plurals else 'string'
    source+='        IDS.put('+json.dumps(english,ensure_ascii=False)+',R.'+kind+'.'+key(english)+');\n'
    if english in plurals:source+='        QUANTITIES.put(R.plurals.'+key(english)+','+str(plurals[english][1])+');\n'
source+='''    }
    private I18n(){}
    public static String tr(Context c,String english,Object... args){
        Integer id=IDS.get(english);String result;
        if(id==null) result=english;
        else if(QUANTITIES.containsKey(id)) result=c.getResources().getQuantityString(id,((Number)args[QUANTITIES.get(id)]).intValue());
        else result=c.getString(id);
        return args.length==0?result:String.format(AppPrefs.locale(c),result,args);
    }
}
'''
(root/'app/src/main/java/fr/mediclogger/app/I18n.java').write_text(source)
print(f'Generated {len(messages)} messages in English, French, Portuguese and Chinese; format placeholders verified.')
