#!/usr/bin/env python3
"""Keep iOS translations and XLSX metadata consistent with Android."""
from pathlib import Path
import re, json
ROOT=Path(__file__).resolve().parent.parent
base=json.loads((ROOT/'app/translations.json').read_text())
base.update(json.loads((ROOT/'ios/Translations-extra.json').read_text()))
(ROOT/'ios/MedicLogger/Translations.json').write_text(json.dumps(base,ensure_ascii=False,indent=2)+'\n')
java=(ROOT/'app/src/main/java/fr/mediclogger/app/ExportWriter.java').read_text()
entries=re.findall(r'entry\(z,"([^"\n]+)",("(?:\\.|[^"\\])*?")\);',java)
assert len(entries)==5, 'Review changed XLSX metadata before generating iOS resources.'
lines=['// Generated by scripts/generate-ios-resources.py.','enum WorkbookMetadata {','    static let files: [String:String] = [']
for name,raw in entries: lines.append('        '+json.dumps(name)+': #"'+json.loads(raw)+'"#,')
lines+=['    ]','}']
(ROOT/'ios/MedicLogger/WorkbookMetadata.swift').write_text('\n'.join(lines)+'\n')
print(f'Generated {len(base)} translations and workbook metadata.')
