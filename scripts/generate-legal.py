#!/usr/bin/env python3
"""Generate bundled, offline legal screens and static public pages from one source."""
from pathlib import Path
import html
import json

ROOT = Path(__file__).resolve().parent.parent
content = json.loads((ROOT / 'assets/legal/content.json').read_text())
translations = json.loads((ROOT / 'app/translations.json').read_text())
assert content['publisher'].strip() and '@' in content['email']
assert content['privacy_url'] is None or content['privacy_url'].startswith('https://')

licenses = ROOT / 'assets/legal/licenses'
notices = [
    'Medic Logger — Android open-source notices',
    'SQLCipher for Android 4.20.0 — Zetetic LLC\nhttps://github.com/sqlcipher/sqlcipher-android',
    (licenses / 'SQLCipher-Android-BSD.txt').read_text(),
    'SQLCipher Community Edition 4.20.0 — Zetetic LLC\nhttps://www.zetetic.net/sqlcipher/',
    (licenses / 'SQLCipher-Community-BSD.txt').read_text(),
    'SQLite and SQLite Android Bindings\nhttps://sqlite.org/copyright.html\nReleased to the public domain. This product includes software developed by the SQLite Project.',
    'LibTomCrypt — SQLCipher Android cryptography provider\nhttps://github.com/libtom/libtomcrypt',
    (licenses / 'LibTomCrypt-Public-Domain.txt').read_text(),
    'AndroidX SQLite 2.7.0 and AndroidX Annotation 1.9.1\nCopyright The Android Open Source Project\nhttps://developer.android.com/jetpack/androidx',
    'Google Play Billing Library 9.1.0\nCopyright Google LLC\nhttps://developer.android.com/google/play/billing',
    'Kotlin standard library 2.2.10\nhttps://github.com/JetBrains/kotlin',
    (licenses / 'Kotlin-NOTICE.txt').read_text(),
    'JetBrains Java annotations 13.0\nJetBrains s.r.o.\nhttps://github.com/JetBrains/java-annotations',
    'AndroidX, Google Play Billing, Kotlin and JetBrains annotations are licensed under the Apache License, Version 2.0:',
    (licenses / 'Apache-2.0.txt').read_text(),
]
notices_text = '\n\n'.join(notices) + '\n'
(ROOT / 'assets/legal/third-party-notices.txt').write_text(notices_text)
raw = ROOT / 'app/src/main/res/raw'
raw.mkdir(exist_ok=True)
(raw / 'third_party_notices.txt').write_text(notices_text)

def quoted(value):
    return json.dumps(value, ensure_ascii=False)

java = ['// Generated by scripts/generate-legal.py; edit assets/legal/content.json.',
        'package fr.mediclogger.app;', '', 'final class LegalContent {']
for key in ['publisher', 'email', 'updated', 'privacy_url']:
    java.append(f'    static final String {key.upper()} = {quoted(content[key])};')
for key in ['privacy', 'medical']:
    java.append(f'    static final String[][] {key.upper()} = {{')
    for section in content[key]:
        java.append('        {' + quoted(section['title']) + ', ' + quoted(section['body']) + '},')
    java.append('    };')
java += ['    private LegalContent() {}', '}']
(ROOT / 'app/src/main/java/fr/mediclogger/app/LegalContent.java').write_text('\n'.join(java) + '\n')

swift = ['// Generated by scripts/generate-legal.py; edit assets/legal/content.json.',
         'enum LegalContent {', '    struct Section: Identifiable {',
         '        let title: String', '        let body: String', '        var id: String { title }', '    }']
for key, name in [('publisher', 'publisher'), ('email', 'email'), ('updated', 'updated')]:
    swift.append(f'    static let {name} = {quoted(content[key])}')
swift.append('    static let privacyURL: String? = ' + (quoted(content['privacy_url']) if content['privacy_url'] else 'nil'))
for key in ['privacy', 'medical']:
    swift.append(f'    static let {key}: [Section] = [')
    for section in content[key]:
        swift.append('        Section(title: ' + quoted(section['title']) + ', body: ' + quoted(section['body']) + '),')
    swift.append('    ]')
swift.append('}')
(ROOT / 'ios/MedicLogger/LegalContent.swift').write_text('\n'.join(swift) + '\n')

destination = ROOT / 'docs/legal'
destination.mkdir(parents=True, exist_ok=True)
languages = [('en', 'English', 'index.html'), ('fr', 'Français', 'privacy-fr.html'),
             ('pt', 'Português', 'privacy-pt.html'), ('zh', '中文', 'privacy-zh.html')]
for language, _, filename in languages:
    def tr(value):
        if language == 'en':
            return value
        assert value in translations, value
        return translations[value][{'fr': 0, 'pt': 1, 'zh': 2}[language]]
    def escape(value):
        return html.escape(value, quote=True)
    navigation = ' · '.join(f'<a href="{file}" lang="{code}">{name}</a>' for code, name, file in languages)
    sections = []
    for key, title in [('privacy', 'Privacy policy'), ('medical', 'Medical notice')]:
        sections.append(f'<section id="{key}"><h1>{escape(tr(title))}</h1>')
        for section in content[key]:
            sections.append(f'<h2>{escape(tr(section["title"]))}</h2><p>{escape(tr(section["body"]))}</p>')
        sections.append('</section>')
    sections.append(f'<footer><h2>{escape(tr("Publisher and contact"))}</h2><p>{escape(content["publisher"])} · <a href="mailto:{escape(content["email"])}">{escape(content["email"])}</a></p><p>{escape(tr("Last updated"))}: <time datetime="{content["updated"]}">{content["updated"]}</time></p></footer>')
    css = ':root{color-scheme:light dark;font:100%/1.65 system-ui,sans-serif;--red:#a52e38}*{box-sizing:border-box}body{max-width:48rem;margin:auto;padding:1.4rem;color:#292326;background:#fff}header{border-bottom:1px solid #eadbde;padding-bottom:1rem}header strong{font-size:1.3rem}nav{margin-top:.6rem}a{color:var(--red);text-underline-offset:.2em}h1{font-size:1.75rem;line-height:1.2;margin-top:2rem}h2{font-size:1.1rem;margin:1.5rem 0 .3rem}p{margin:.3rem 0 1rem}footer{margin-top:2rem;border-top:1px solid #eadbde}a:focus-visible{outline:3px solid var(--red);outline-offset:4px}@media(prefers-color-scheme:dark){body{background:#181517;color:#f5ecee;--red:#ffabb2}header,footer{border-color:#584247}}'
    page = f'<!doctype html>\n<html lang="{language}"><head><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><meta name="description" content="{escape(tr("Privacy policy"))} — Medic Logger"><title>Medic Logger — {escape(tr("Privacy policy"))}</title><style>{css}</style></head><body><header><strong>Medic Logger</strong><nav aria-label="{escape(tr("Language"))}">{navigation}</nav></header><main>{"".join(sections)}</main></body></html>\n'
    (destination / filename).write_text(page)

print('Generated offline legal content for both apps and four static public pages.')
